-- ============================================================
-- 登录链路与系统基础表
-- ============================================================

-- 通用：updated_at 自动维护
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ------------------------------------------------------------
-- 1. sys_user 用户
-- ------------------------------------------------------------
CREATE TABLE sys_user (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username             varchar(64)  NOT NULL,
    password_hash        varchar(100) NOT NULL,          -- BCrypt(cost=10)
    nickname             varchar(64),
    email                varchar(128),
    role                 varchar(20)  NOT NULL DEFAULT 'USER'
                         CHECK (role IN ('USER','ADMIN','SUPERADMIN')),
    status               varchar(16)  NOT NULL DEFAULT 'ENABLED'
                         CHECK (status IN ('ENABLED','DISABLED')),
    must_change_password boolean      NOT NULL DEFAULT false,
    last_login_at        timestamptz,
    created_by           bigint REFERENCES sys_user(id),
    created_at           timestamptz  NOT NULL DEFAULT now(),
    updated_at           timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_sys_user_username UNIQUE (username)
);

COMMENT ON TABLE  sys_user IS '用户账号主体';
COMMENT ON COLUMN sys_user.must_change_password IS '重置密码或初始密码登录后为 true，强制修改后才能正常使用';
COMMENT ON COLUMN sys_user.password_hash IS 'BCrypt，cost=10，60 字符';

CREATE TRIGGER trg_sys_user_updated BEFORE UPDATE ON sys_user
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 登录时按用户名查，唯一约束已建索引；这里为「禁用账号快速判断」加一个复合索引
CREATE INDEX idx_sys_user_status ON sys_user (status) WHERE status = 'DISABLED';

-- ------------------------------------------------------------
-- 2. sys_refresh_token 刷新令牌
--    · 热状态（是否吊销）在 Redis: wenqu:auth:refresh:{jti}
--    · 本表用于审计、故障恢复与「改密后吊销全部令牌」
-- ------------------------------------------------------------
CREATE TABLE sys_refresh_token (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint      NOT NULL REFERENCES sys_user(id) ON DELETE CASCADE,
    jti        varchar(64) NOT NULL,                     -- JWT ID，令牌唯一标识
    expires_at timestamptz NOT NULL,
    revoked    boolean     NOT NULL DEFAULT false,
    user_agent varchar(255),
    ip         varchar(64),
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uk_refresh_jti UNIQUE (jti)
);

CREATE INDEX idx_refresh_user ON sys_refresh_token (user_id);
CREATE INDEX idx_refresh_exp  ON sys_refresh_token (expires_at);   -- 定期清理过期令牌

COMMENT ON TABLE sys_refresh_token IS 'Refresh Token 记录；登出/改密/禁用用户时置 revoked=true';

-- ------------------------------------------------------------
-- 3. sys_login_attempt 登录尝试（审计 + 失败计数持久化）
--    实时计数仍在 Redis: wenqu:auth:loginfail:{username}
-- ------------------------------------------------------------
CREATE TABLE sys_login_attempt (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username     varchar(64) NOT NULL,
    ip           varchar(64),
    success      boolean     NOT NULL,
    attempted_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_login_attempt_user ON sys_login_attempt (username, attempted_at DESC);

COMMENT ON TABLE sys_login_attempt IS '登录成功/失败流水；失败 5 次锁定 30 分钟由 sys_setting 控制';

-- ------------------------------------------------------------
-- 4. sys_operation_log 操作日志（审计）
-- ------------------------------------------------------------
CREATE TABLE sys_operation_log (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint,
    username   varchar(64),
    type       varchar(32)  NOT NULL,   -- LOGIN / KB / DOC / CHAT / SQL / SYSTEM
    action     varchar(128) NOT NULL,
    target     varchar(255),
    detail     text,
    ip         varchar(64),
    user_agent varchar(255),
    result     varchar(16)  NOT NULL DEFAULT 'SUCCESS',  -- SUCCESS / FAILURE
    trace_id   varchar(64),
    created_at timestamptz  NOT NULL DEFAULT now()
);

CREATE INDEX idx_oplog_created ON sys_operation_log (created_at DESC);
CREATE INDEX idx_oplog_user    ON sys_operation_log (user_id, created_at DESC);
CREATE INDEX idx_oplog_type    ON sys_operation_log (type);

-- ------------------------------------------------------------
-- 5. sys_setting 系统参数
-- ------------------------------------------------------------
CREATE TABLE sys_setting (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key         varchar(128) NOT NULL,
    value       text,
    value_type  varchar(16)  NOT NULL DEFAULT 'STRING',  -- STRING/INT/DOUBLE/BOOLEAN/JSON
    group_name  varchar(32)  NOT NULL DEFAULT 'SYSTEM',
    description varchar(255),
    updated_by  bigint,
    created_at  timestamptz  NOT NULL DEFAULT now(),
    updated_at  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_setting_key UNIQUE (key)
);

CREATE TRIGGER trg_setting_updated BEFORE UPDATE ON sys_setting
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

